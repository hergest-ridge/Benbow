package app.benbow.app

import app.benbow.ui.theme.ThemeContrast
import app.benbow.ui.theme.ThemePalette
import app.benbow.ui.theme.ThemeSpec
import app.benbow.ui.theme.colorsOf
import app.benbow.ui.theme.hex
import app.benbow.ui.theme.schemeOf
import java.io.File
import kotlin.test.Test
import kotlin.test.assertTrue

/**
 * What draws before the app or beside it wears the app's colors (ADR-057), from the one generator: the Android window
 * before its first frame, the web's loading page and the server's admin page. Each keeps a block made here; when the
 * theme changes, this test writes the new block and fails once, so the change is seen and committed.
 */
class ThemeFilesTest {
    private val root = File("../..")

    private fun scheme(dark: Boolean, contrast: ThemeContrast = ThemeContrast.Standard) =
        schemeOf(ThemeSpec(ThemePalette.Inn, contrast = contrast.level), dark)

    @Test
    fun androidsWindowWearsThePageBeforeItsFirstFrame() = check(
        listOf(false to "values", true to "values-night").map { (dark, folder) ->
            File(root, "apps/android/src/main/res/$folder/theme_colors.xml") to whole(
                """
                <?xml version="1.0" encoding="utf-8"?>
                <!-- Generated by ThemeFilesTest from BenbowTheme.kt (ADR-057): the default palette's page. -->
                <resources>
                    <color name="benbow_page">${scheme(dark).background.hex()}</color>
                </resources>
                """.trimIndent() + "\n",
            )
        },
    )

    @Test
    fun theWebsLoadingPageWearsTheDefaultsUntilTheAppTellsIt() = check(
        listOf(
            File(root, "apps/web/src/wasmJsMain/resources/theme.js") to between(
                listOf(false to "light", true to "night").joinToString("\n") { (dark, name) ->
                    val s = scheme(dark)
                    "    var $name = { page: '${s.background.hex()}', accent: '${s.primary.hex()}', quiet: '${s.onSurfaceVariant.hex()}' };"
                },
            ),
        ),
    )

    @Test
    fun theAdminPageWearsTheInn() = check(
        listOf(
            File(root, "server/src/main/resources/admin/admin.css") to between(
                listOf(
                    block(dark = false),
                    media("(prefers-color-scheme: dark)", block(dark = true)),
                    media("(prefers-contrast: more)", block(dark = false, ThemeContrast.High)),
                    media(
                        "(prefers-contrast: more) and (prefers-color-scheme: dark)",
                        block(dark = true, ThemeContrast.High),
                    ),
                ).joinToString("\n"),
            ),
        ),
    )

    private fun block(dark: Boolean, contrast: ThemeContrast = ThemeContrast.Standard): String {
        val s = scheme(dark, contrast)
        val roles = colorsOf(ThemeSpec(ThemePalette.Inn, contrast = contrast.level), dark)
        val vars = listOf(
            "primary" to s.primary, "on-primary" to s.onPrimary,
            "primary-container" to s.primaryContainer, "on-primary-container" to s.onPrimaryContainer,
            "secondary" to s.secondary, "on-secondary" to s.onSecondary,
            "secondary-container" to s.secondaryContainer, "on-secondary-container" to s.onSecondaryContainer,
            "tertiary" to s.tertiary, "tertiary-container" to s.tertiaryContainer, "on-tertiary-container" to s.onTertiaryContainer,
            "error" to s.error, "on-error" to s.onError, "error-container" to s.errorContainer, "on-error-container" to s.onErrorContainer,
            "surface" to s.background, "on-surface" to s.onSurface, "surface-variant" to s.surfaceVariant,
            "on-surface-variant" to s.onSurfaceVariant,
            "outline" to s.outline, "outline-variant" to s.outlineVariant,
            "surface-container-lowest" to s.surfaceContainerLowest, "surface-container-low" to s.surfaceContainerLow,
            "surface-container" to s.surfaceContainer, "surface-container-high" to s.surfaceContainerHigh,
            "surface-container-highest" to s.surfaceContainerHighest,
            "inverse-surface" to s.inverseSurface, "inverse-on-surface" to s.inverseOnSurface, "inverse-primary" to s.inversePrimary,
        ).map { (name, color) -> "--md-$name" to color } + listOf(
            "--ok" to roles.tokens.text("green", dark)!!,
            "--ok-container" to roles.swatches.fill("mint", dark)!!,
            "--on-ok-container" to s.onSurface,
        )
        val lines = vars.chunked(LINE).joinToString("\n") { line ->
            "  " +
                line.joinToString(" ") { (name, color) -> "$name:${color.hex()};" }
        }
        return ":root {\n$lines\n  color-scheme: ${if (dark) "dark" else "light"};\n}"
    }

    private fun media(query: String, inner: String) = "@media $query {\n" + inner.prependIndent("  ") + "\n}"

    /** The whole file is the block. */
    private fun whole(content: String): (String?) -> String = { content }

    /** The block between `theme:begin` and `theme:end`, the rest of the file as it is. */
    private fun between(content: String): (String?) -> String = { old ->
        val text = old ?: error("no file")
        val begin = text.indexOf(BEGIN).also { require(it >= 0) { "no $BEGIN" } } + BEGIN.length
        val end = text.indexOf(END, begin).also { require(it >= 0) { "no $END" } }
        val head = text.substring(0, begin)
        head + "\n" + content + "\n" + text.substring(text.lastIndexOf('\n', end) + 1)
    }

    private fun check(files: List<Pair<File, (String?) -> String>>) {
        val stale = files.mapNotNull { (file, make) ->
            val old = file.takeIf { it.exists() }?.readText()?.replace("\r\n", "\n")
            val new = make(old)
            if (old == new) null else file.also { it.writeText(new) }
        }
        assertTrue(stale.isEmpty(), "rewritten from the theme, run again and commit: ${stale.joinToString { it.path }}")
    }

    private companion object {
        const val BEGIN = "/* theme:begin */"
        const val END = "/* theme:end */"
        const val LINE = 4
    }
}
